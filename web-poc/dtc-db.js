function describeDTC(code) {
  if (DTC_DB[code]) return t(DTC_DB[code]);
  const sys = t({ P: 'Powertrain', C: 'Chassis', B: 'Body', U: 'Network' }[code[0]]);
  const none = t('no description in the built-in list');
  if (code[1] === '1' || code[1] === '3' && code[0] !== 'P') return `${sys}: ${t('manufacturer-specific code')}`;
  if (code[0] === 'P') {
    const groups = { 0: 'fuel and air metering', 1: 'fuel and air metering', 2: 'fuel and air metering (injector circuit)', 3: 'ignition system or misfire',
      4: 'auxiliary emission controls', 5: 'vehicle speed, idle control and auxiliary inputs', 6: 'computer and output circuits', 7: 'transmission', 8: 'transmission', 9: 'transmission' };
    return `${sys}: ${t(groups[code[2]] || 'generic')} (${none})`;
  }
  return `${sys}: ${t('generic code')} (${none})`;
}
